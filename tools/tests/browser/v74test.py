# v0.74: KT-/SEK-Codes über Bedingungen, eigener Codesatz, Editor mit Prüfung und Entwurf
import subprocess, sys, time, json, re
from playwright.sync_api import sync_playwright
S = sys.argv[1]; DIST = sys.argv[2]
fails = 0; logs = []
def check(ok, w):
    global fails
    print(("OK    " if ok else "FEHLER"), w)
    if not ok: fails += 1
srv = subprocess.Popen([sys.executable, "-m", "http.server", "8874", "-d", DIST], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1)
J = "window.__lw.sim"
EIGEN = re.compile(r"^(KT[ARx]-9[035][TCRD][1-4][SA]?|SEK-96[GSN][1-7](-\w+)?)$")
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        ctx = b.new_context(viewport={"width": 1600, "height": 950})
        ctx.route("https://tickets.leitwerk.workers.dev/**", lambda r: r.abort())
        A = ctx.new_page(); A.on("pageerror", lambda e: logs.append(str(e)))
        A.add_init_script("localStorage.setItem('leitwerk.persoenlich', JSON.stringify({thema: 'dunkel', einfuehrung: true}))")
        A.goto("http://localhost:8874/?debug"); A.wait_for_timeout(2500)
        A.evaluate("() => { const st = structuredClone(window.__lw.store.settings); st.generatorAktiv = false; window.__lw.store.setSettings(st); window.__lw.kiPrefsSetzen({ aktiv: false }); }")
        A.evaluate(f"() => {{ const s={J}; const d=new Date(s.state.zeit); d.setHours(9,0,0,0); s.state.zeit=d.getTime(); }}")
        A.evaluate(f"() => {J}.call('start')"); A.wait_for_timeout(1200); A.evaluate(f"() => {J}.call('pause')")
        # --- eingebaut: eigene Codes
        r = A.evaluate(f"""async () => {{ const s={J}; const out=[]; for (let i=0;i<12;i++) {{ const k=await s.generiereKt('online'); if(k) out.push(k.d.code); }} for (let i=0;i<12;i++) {{ const k=await s.generiereSek('online'); if(k) out.push(k.d.code); }} return out; }}""")
        print("   ", r)
        check(len(r) >= 20 and all(c and EIGEN.match(c) for c in r), f"eingebaute eigene KT-/SEK-Codes für alle Aufträge ({len(r)})")
        check(any(c.startswith("SEK-") for c in r) and any(c.startswith("KT") for c in r), "KT und SEK vertreten")
        def vorschlag(code):
            kid = A.evaluate(f"() => ({J}.state.kt||[]).find(k=>k.d.code && k.d.code.startsWith('SEK-'))?.id")
            A.evaluate(f"(a) => {J}.call('ktSetze', a[0], {{ code: a[1] }})", [kid, code])
            return A.evaluate(f"async (id) => (await {J}.ktVorschlaege(id)).filter(v => !v.ersatz).slice(0,3).map(v=>v.fz.rmTyp)", kid)
        v1 = vorschlag("SEK-96G4"); v2 = vorschlag("SEK-96G5-SRTW"); v3 = vorschlag("SEK-96G6-SNAW")
        print("   ", v1, v2, v3)
        check((not v1 or v1[0] == "SKTW") and (not v2 or v2[0] == "SRTW") and (not v3 or v3[0] == "SNAW"), "Fahrzeuge aus den Bedingungen: SKTW / SRTW / SNAW")
        # --- Editor: Prüfung, Entwurf, ergänzen
        A.evaluate("() => window.__lw.startseite.zeigen()"); A.wait_for_timeout(900)
        A.click('.st [data-act="einstellungen"]'); A.wait_for_timeout(800)
        A.click('[data-seite="codes"]'); A.wait_for_timeout(800)
        A.click('[data-act-codes="saetze"]'); A.wait_for_timeout(700)
        A.click("[data-kt-editor]"); A.wait_for_timeout(800)
        st = A.inner_text(".kte-status")
        check("Alles vollständig" in st, f"eingebauter Satz vollständig: {st}")
        A.fill(".kte-suche", "KTA-93D4"); A.wait_for_timeout(300)
        A.locator(".kte-zeile", has_text="KTA-93D4").locator("button", has_text="✕").click(); A.wait_for_timeout(400)
        st = A.inner_text(".kte-status"); fl = A.inner_text(".kte-liste")
        dis = A.evaluate("() => document.querySelector('.kte-dlg .dlg-foot .btn.primary')?.disabled")
        print("   ", st, "|", fl[:160].replace("\n", " / "))
        check("Problem" in st and "Kein Code für" in fl and "Dialyse" in fl and dis, "fehlender Code wird gemeldet, nur Entwurf möglich")
        A.fill('.kte input[name="satzname"]', "Test KT")
        A.locator(".kte-dlg .dlg-foot .btn", has_text="Als Entwurf").click(); A.wait_for_timeout(1000)
        z = A.evaluate("() => [...document.querySelectorAll('.cs-satz')].map(x => x.textContent.replace(/\\s+/g,' ').trim())")
        print("   ", z)
        check(any("Test KT" in x and "ENTWURF" in x for x in z), "Entwurf in der Liste")
        check(A.evaluate("() => { const r = [...document.querySelectorAll('.cs-satz')].find(x => x.textContent.includes('Test KT')); return r.querySelector('button').disabled; }"), "Entwurf ist nicht verwendbar")
        A.locator(".cs-satz", has_text="Test KT").locator("button", has_text="Bearbeiten").click(); A.wait_for_timeout(800)
        A.locator(".kte-liste li.fehler button", has_text="Code anlegen").first.click(); A.wait_for_timeout(400)
        bed = A.evaluate("() => ({ fahrt: document.querySelector('.kte-form select[name=bed-fahrt]').value, therapie: document.querySelector('.kte-form select[name=bed-therapie]').value, lage: document.querySelector('.kte-form select[name=bed-lage]').value })")
        A.fill('.kte-form input[name="code"]', "KTA-DIALYSE-LIEGEND"); A.fill('.kte-form input[name="name"]', "Dialyse liegend (ASB)"); A.wait_for_timeout(300)
        st = A.inner_text(".kte-status")
        check(bed["therapie"] == "dialyse" and "Alles vollständig" in st, f"„Code anlegen“ übernimmt die fehlende Kombination {bed} → vollständig")
        A.locator(".kte-dlg .dlg-foot .btn.primary").click(); A.wait_for_timeout(1500)
        aktiv = A.evaluate("() => [...document.querySelectorAll('.cs-satz.aktiv')].map(x => x.textContent)")
        check(any("Test KT" in x for x in aktiv) and A.evaluate("() => window.__lw.store.ktSatzRoh?.name") == "Test KT", "fertiger Satz gespeichert und aktiv")
        # Abfrage: Pflichtfrage abschalten
        A.click("[data-kt-editor]"); A.wait_for_timeout(700)
        A.click('[data-kte="abfrage"]'); A.wait_for_timeout(300)
        A.click('[data-frage="lage"] [data-frage-act="loeschen"]'); A.wait_for_timeout(300)
        fl = A.inner_text(".kte-liste")
        check("Lage" in fl and "keine Frage" in fl, "Abfrage ohne Lage-Frage wird gemeldet")
        A.click('[data-frage="art"] [data-frage-act="loeschen"]'); A.wait_for_timeout(300)
        fl = A.inner_text(".kte-pruefung")
        check("Organisation" in fl, f"Codes unterscheiden nach Organisation, Abfrage fragt nicht → Hinweis")
        A.screenshot(path=f"{S}/v74_editor.png")
        A.locator(".kte-dlg .dlg-foot .btn", has_text="Abbrechen").click(); A.wait_for_timeout(300)
        A.locator(".dlg-foot .btn", has_text="Schließen").last.click(); A.wait_for_timeout(300)
        # --- echter Satz (Testkopie) mit echten KT-/SEK-Codes
        A.evaluate("async () => window.__lw.codesystemLaden(await (await fetch('/abf_test.json')).json())"); A.wait_for_timeout(800)
        r2 = A.evaluate(f"""async () => {{ const s={J}; const out=[]; for (let i=0;i<8;i++) {{ const k=await s.generiereKt('online'); if(k) out.push(k.d.code); }} for (let i=0;i<10;i++) {{ const k=await s.generiereSek('online'); if(k) out.push(k.d.code); }} return out; }}""")
        print("   ", r2)
        check(len(r2) >= 15 and all(c and re.match(r"^(KT[ARx]-9[035][KMSY][1-4]A?!?|SEK-96[KBD]\d!?(-\w+)?)$", c) for c in r2), "mit dem eigenen Satz gelten dessen KT-/SEK-Codes")
        check(not any(c.startswith(("KTx-96", "KTA-96", "KTR-96")) for c in r2), "Überstellungen immer SEK")
        if not A.locator('[data-act-codes="saetze"]').is_visible():
            A.evaluate("() => window.__lw.startseite.zeigen()"); A.wait_for_timeout(900)
            A.click('.st [data-act="einstellungen"]'); A.wait_for_timeout(800)
            A.click('[data-seite="codes"]'); A.wait_for_timeout(800)
        A.click('[data-act-codes="saetze"]'); A.wait_for_timeout(700)
        A.click("[data-kt-editor]"); A.wait_for_timeout(800)
        st = A.inner_text(".kte-status"); print("   ", st, A.inner_text(".kte-pruefung")[:300].replace("\n", " / "))
        check("Alles vollständig" in st and "136" in st, f"echte KT-/SEK-Codes vollständig und eindeutig: {st}")
        A.locator(".kte-dlg .dlg-foot .btn", has_text="Abbrechen").click(); A.wait_for_timeout(300)
        A.locator(".dlg-foot .btn", has_text="Schließen").last.click(); A.wait_for_timeout(300)
        # fehlender Code im Auftrag: deutlicher Hinweis
        A.evaluate("() => { const k = structuredClone(window.__lw.store.ktSatzRoh); k.codes = k.codes.filter(c => c.bed.fahrt !== 'zum_kh'); window.__lw.store.setKtSatz(k); }"); A.wait_for_timeout(500)
        kid = A.evaluate(f"""() => {{ const s={J}; s.call('ktNeuManuell'); return s.state.kt[0].id; }}""")
        A.evaluate(f"(id) => {J}.call('ktSetze', id, {{ lage: 'liegend', von: {{ lat: 48.4, lon: 15.6, label: 'Krems' }}, nach: {{ lat: 48.41, lon: 15.61, label: 'Krems 2' }} }})", kid)
        code = A.evaluate(f"(id) => {J}.ktAuftrag(id).d.code", kid)
        check(code is None, f"ohne passenden Code bleibt der Code leer ({code})")
        check(not logs, f"keine Fehler im Programm {logs[:3]}")
        b.close()
finally:
    srv.terminate()
print(f"FEHLER: {fails}")
